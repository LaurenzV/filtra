//! Generates the WGSL and GLSL of `filtra_shaders`. Run it after changing a shader.

mod minify;

use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use naga::back::glsl;
use naga::valid::{Capabilities, ValidationFlags, Validator};
use wesl::Wesl;

const HEADER: &str = "Generated by `cargo run -p filtra_shaders_gen`. Do not edit.";

fn main() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).parent().unwrap();
    let shaders = root.join("shaders");
    let generated = root.join("generated");
    fs::create_dir_all(&generated).unwrap();

    let mut compiler = Wesl::new(&shaders);
    compiler.use_stripping(true);
    let link = |name: &str| {
        let wgsl = compiler
            .compile(&format!("package::{name}").parse().unwrap())
            .unwrap_or_else(|error| panic!("{name}: {error}"))
            .to_string();
        minify::minify_wgsl(&wgsl)
    };

    let mut names: Vec<String> = fs::read_dir(&shaders)
        .unwrap()
        .map(|entry| entry.unwrap().path())
        .filter(|path| {
            path.extension()
                .is_some_and(|extension| extension == "wesl")
        })
        .map(|path| path.file_stem().unwrap().to_string_lossy().into_owned())
        .filter(|name| name != "vertex")
        .collect();
    names.sort();

    let vertex = link("vertex");
    let (vertex_glsl, _) = glsl(&vertex, naga::ShaderStage::Vertex, "vertex");
    write(
        &generated.join("vertex.wgsl"),
        &format!("// {HEADER}\n{vertex}\n"),
    );
    write(&generated.join("vertex.vert"), &vertex_glsl);

    let mut rust = format!("// {HEADER}\n\nuse crate::Shader;\n\n");
    let mut arms = String::new();

    for name in &names {
        let wgsl = link(name);
        let (fragment, reflection) = glsl(&wgsl, naga::ShaderStage::Fragment, name);
        write(
            &generated.join(format!("{name}.wgsl")),
            &format!("// {HEADER}\n{wgsl}\n"),
        );
        write(&generated.join(format!("{name}.frag")), &fragment);

        let textures: Vec<String> = reflection
            .textures
            .iter()
            .map(|t| format!("{t:?}"))
            .collect();
        write!(
            arms,
            "        Shader::{variant} => Generated {{\n            wgsl: include_str!(\"../generated/{name}.wgsl\"),\n            glsl: include_str!(\"../generated/{name}.frag\"),\n            glsl_uniform_block: {block:?},\n            glsl_textures: &[{textures}],\n        }},\n",
            variant = camel_case(name),
            block = reflection.uniform_block,
            textures = textures.join(", "),
        )
        .unwrap();
    }

    write!(
        rust,
        "pub(crate) const VERTEX_WGSL: &str = include_str!(\"../generated/vertex.wgsl\");\n\
         pub(crate) const VERTEX_GLSL: &str = include_str!(\"../generated/vertex.vert\");\n\n\
         pub(crate) struct Generated {{\n    pub(crate) wgsl: &'static str,\n    pub(crate) glsl: &'static str,\n    pub(crate) glsl_uniform_block: &'static str,\n    pub(crate) glsl_textures: &'static [&'static str],\n}}\n\n\
         pub(crate) const fn generated(shader: Shader) -> Generated {{\n    match shader {{\n{arms}    }}\n}}\n"
    )
    .unwrap();
    write(&root.join("src").join("generated.rs"), &rust);
}

struct Reflection {
    uniform_block: String,
    textures: Vec<String>,
}

fn glsl(wgsl: &str, stage: naga::ShaderStage, name: &str) -> (String, Reflection) {
    let module = naga::front::wgsl::parse_str(wgsl)
        .unwrap_or_else(|error| panic!("{name}: {}", error.emit_to_string(wgsl)));
    let info = Validator::new(ValidationFlags::all(), Capabilities::empty())
        .validate(&module)
        .unwrap_or_else(|error| panic!("{name}: {}", error.emit_to_string(wgsl)));
    let options = glsl::Options {
        version: glsl::Version::Embedded {
            version: 300,
            is_webgl: true,
        },
        ..Default::default()
    };
    let pipeline_options = glsl::PipelineOptions {
        shader_stage: stage,
        entry_point: "main".to_owned(),
        multiview: None,
    };
    let mut out = String::new();
    let mut writer = glsl::Writer::new(
        &mut out,
        &module,
        &info,
        &options,
        &pipeline_options,
        naga::proc::BoundsCheckPolicies::default(),
    )
    .unwrap_or_else(|error| panic!("{name}: {error}"));
    let reflection = writer
        .write()
        .unwrap_or_else(|error| panic!("{name}: {error}"));

    let uniform_block = reflection
        .uniforms
        .values()
        .next()
        .cloned()
        .unwrap_or_default();
    let mut textures: Vec<(u32, String)> = reflection
        .texture_mapping
        .iter()
        .map(|(glsl_name, mapping)| {
            let binding = module.global_variables[mapping.texture]
                .binding
                .as_ref()
                .unwrap();
            (binding.binding, glsl_name.clone())
        })
        .collect();
    textures.sort();

    let reflection = Reflection {
        uniform_block,
        textures: textures.into_iter().map(|(_, name)| name).collect(),
    };
    // `#version` has to stay on the first line.
    let minified = minify::minify_glsl(&out);
    let (version, rest) = minified.split_once('\n').unwrap();
    (format!("{version}\n// {HEADER}\n{rest}\n"), reflection)
}

fn write(path: &Path, contents: &str) {
    fs::write(path, contents).unwrap();
}

fn camel_case(name: &str) -> String {
    name.split('_')
        .map(|part| {
            let mut chars = part.chars();
            chars
                .next()
                .unwrap()
                .to_uppercase()
                .chain(chars)
                .collect::<String>()
        })
        .collect()
}
